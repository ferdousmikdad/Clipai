#!/usr/bin/env node
// License check + THIRD_PARTY_NOTICES.md generator for production dependencies.
//   node scripts/licenses.mjs --check    fail on any non-allowed license
//   node scripts/licenses.mjs --notice   (re)write THIRD_PARTY_NOTICES.md
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ALLOWED = new Set(["MIT", "ISC", "BSD-2-Clause", "BSD-3-Clause", "Apache-2.0", "MPL-2.0", "0BSD", "Unlicense"]);

function normalize(license) {
  if (!license) return [];
  // "(MIT OR Apache-2.0)" → any allowed choice is fine
  return String(license).replace(/[()]/g, "").split(/\s+OR\s+/i).map((s) => s.trim());
}

const json = execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], { cwd: root, encoding: "utf8", shell: process.platform === "win32", maxBuffer: 64 * 1024 * 1024 });
const byLicense = JSON.parse(json);
const packages = [];
for (const [license, list] of Object.entries(byLicense)) {
  for (const p of list) {
    for (const version of p.versions ?? [p.version]) {
      packages.push({ name: p.name, version, license, paths: p.paths ?? [], homepage: p.homepage, author: p.author });
    }
  }
}
packages.sort((a, b) => a.name.localeCompare(b.name));

const bad = packages.filter((p) => !p.name.startsWith("@clipai/") && !normalize(p.license).some((l) => ALLOWED.has(l)));

if (process.argv.includes("--check")) {
  if (bad.length) {
    console.error("Disallowed licenses in production dependencies:");
    for (const p of bad) console.error(`  ${p.name}@${p.version}: ${p.license}`);
    console.error(`Allowed: ${[...ALLOWED].join(", ")}`);
    process.exit(1);
  }
  console.log(`License check passed (${packages.length} production packages).`);
}

if (process.argv.includes("--notice")) {
  const licenseText = (dir) => {
    if (!dir || !existsSync(dir)) return "";
    const f = readdirSync(dir).find((n) => /^(licen[cs]e|copying)(\.|$)/i.test(n));
    return f ? readFileSync(path.join(dir, f), "utf8").trim() : "";
  };
  const out = [
    "# Third-party notices",
    "",
    "Clipai is MIT licensed. It depends on the open-source packages below, which keep their own licenses.",
    "Generated by `pnpm licenses:notice` — do not edit by hand.",
    "",
    "## Bundled fonts and icons",
    "",
    "- Inter, Poppins, Hind Siliguri, Noto Sans Bengali — SIL Open Font License 1.1 (see `assets/licenses/`).",
    "- Lucide icons — ISC License (see `assets/licenses/lucide-LICENSE.txt`).",
    "",
    "## npm packages (production)",
    "",
  ];
  for (const p of packages.filter((p) => !p.name.startsWith("@clipai/"))) {
    out.push(`### ${p.name}@${p.version} — ${p.license}`, "");
    if (p.homepage) out.push(p.homepage, "");
    const text = licenseText(p.paths[0]);
    if (text) out.push("```", text, "```", "");
  }
  writeFileSync(path.join(root, "THIRD_PARTY_NOTICES.md"), out.join("\n"));
  console.log(`Wrote THIRD_PARTY_NOTICES.md (${packages.length} packages).`);
}
